export function formatMoney(amount: number, lang: Language): string {
  const formatted = amount.toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return lang === 'ar' ? `${formatted} ر.س` : `${formatted} SAR`;
}

export function formatDateTime(iso: string, lang: Language): string {
  const date = new Date(iso);
  return date.toLocaleString(lang === 'ar' ? 'ar-SA' : 'en-GB', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
  });
}
